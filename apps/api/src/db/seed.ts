export async function seed() {
  for (const [index, direction] of directions.entries()) {
    const [row] = await sql`
      INSERT INTO directions (slug, name, description, emoji, color, display_order)
      VALUES (${direction.slug}, ${direction.name}, ${direction.description}, ${direction.emoji}, ${direction.color}, ${index})
      ON CONFLICT (slug) DO UPDATE SET
        name = EXCLUDED.name, description = EXCLUDED.description, emoji = EXCLUDED.emoji,
        color = EXCLUDED.color, display_order = EXCLUDED.display_order, active = true
      RETURNING id
    `;
    for (const [habitIndex, habit] of direction.habits.entries()) {
      await sql`
        INSERT INTO habit_templates (direction_id, name, description, default_frequency, default_days, display_order)
        VALUES (${row.id}, ${habit[0]}, ${habit[1]}, ${habit[2]}, ${habit[3]}, ${habitIndex})
        ON CONFLICT (direction_id, name) DO UPDATE SET
          description = EXCLUDED.description, default_frequency = EXCLUDED.default_frequency,
          default_days = EXCLUDED.default_days, display_order = EXCLUDED.display_order, active = true
      `;
    }
  }

  for (const text of messages) {
    await sql`
      INSERT INTO messages (kind, text) VALUES ('support', ${text})
      ON CONFLICT (kind, text) DO UPDATE SET active = true
    `;
  }
  console.log(`Seeded ${directions.length} directions and ${messages.length} messages`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  seed().then(() => sql.end()).catch(async (error) => {
    console.error(error);
    await sql.end();
    process.exit(1);
  });
}
